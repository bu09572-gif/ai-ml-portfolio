"""Build the requirements register from the state AI rules and the governance report for my models.

    python run.py    # -> results/requirements.jsonl, results/summary.json, results/governance_report.md
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

import data
import governance as g

OUT = Path(__file__).resolve().parent / "results"
NAMES = {"naic_bulletin": "NAIC model bulletin", "new_york": "New York CL 7 (2024)", "colorado": "Colorado Reg. 10-1-1"}
MODELS = {
    "projects/insurance/motor-pricing-fairness": "Motor pricing (frequency x severity, discrimination-free premium)",
    "projects/insurance/claims-severity-large-loss": "Motor claim severity and large-loss load",
    "projects/finance/explainable-credit-risk": "Credit default model (for comparison: a model built with reasons and fairness tests)",
    "projects/finance/realtime-fraud-scoring": "Card fraud scoring (for comparison)",
}
MARK = {"found": "found", "partial": "partial", "gap": "**gap**"}


def report(reqs, cw, ev, adoption) -> str:
    lines = ["# Governance report: my models against state AI rules for insurers", "",
             f"Generated by `run.py` from {len(reqs)} requirement sentences in 3 rule texts. "
             f"{len(adoption['adopted'])} states and territories had adopted the NAIC bulletin as of {adoption['status_date']}; "
             f"{', '.join(adoption['own_rules'])} have their own rules.", "",
             "## Which rules ask for what (requirement sentences per theme)", "",
             "| Theme | " + " | ".join(NAMES[r] for r in data.RULES) + " |", "|---|" + "---|" * len(data.RULES)]
    for t, row in cw.items():
        lines.append(f"| {t} | " + " | ".join(str(row.get(r, 0)) for r in data.RULES) + " |")
    lines += ["", "## Evidence per model", ""]
    themes = list(g.THEMES)
    lines.append("| Theme | " + " | ".join(m.split("/")[-1] for m in MODELS) + " |")
    lines.append("|---|" + "---|" * len(MODELS))
    for t in themes:
        lines.append(f"| {t} | " + " | ".join(MARK[ev[m][t]["status"]] for m in MODELS) + " |")
    for m, title in MODELS.items():
        lines += ["", f"### {m.split('/')[-1]}: {title}", "", "| Theme | Status | Evidence |", "|---|---|---|"]
        lines += [f"| {t} | {MARK[e['status']]} | {e['evidence']} |" for t, e in ev[m].items()]
    lines += ["", "## Example requirements behind each theme", ""]
    for t in themes:
        ex = [r for r in reqs if t in r["themes"]][:2]
        lines.append(f"**{t}**")
        lines += [f"- {NAMES[r['rule']]}, p. {r['page']}: \"{r['text'][:300]}{'...' if len(r['text']) > 300 else ''}\"" for r in ex]
        lines.append("")
    return "\n".join(lines)


def main():
    reqs = [r for k in data.RULES for r in g.requirements(data.text(k), k)]
    cw = g.crosswalk(reqs)
    ev = {m: g.evidence(m) for m in MODELS}
    adoption = data.adoption()
    OUT.mkdir(exist_ok=True)
    with (OUT / "requirements.jsonl").open("w") as fh:
        for r in reqs:
            fh.write(json.dumps(r) + "\n")
    summary = {"requirements": dict(Counter(r["rule"] for r in reqs)), "untagged_requirements": sum(not r["themes"] for r in reqs),
               "theme_tags": sum(len(r["themes"]) for r in reqs), "crosswalk": cw,
               "naic_bulletin_adoption": {"status_date": adoption["status_date"], "adopted": len(adoption["adopted"]),
                                          "states": adoption["adopted"], "own_rules": adoption["own_rules"]},
               "evidence_status": {m.split("/")[-1]: dict(Counter(e["status"] for e in ev[m].values())) for m in MODELS}}
    (OUT / "summary.json").write_text(json.dumps(summary, indent=2))
    (OUT / "governance_report.md").write_text(report(reqs, cw, ev, adoption))
    print(json.dumps({k: v for k, v in summary.items() if k != "crosswalk"}, indent=2))


if __name__ == "__main__":
    main()
